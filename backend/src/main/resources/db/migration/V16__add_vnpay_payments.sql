ALTER TABLE orders DROP CONSTRAINT orders_payment_method_check;
ALTER TABLE orders ADD CONSTRAINT orders_payment_method_check CHECK (payment_method IN ('COD', 'VNPAY'));
ALTER TABLE orders
    ADD COLUMN payment_status VARCHAR(30) NOT NULL DEFAULT 'UNPAID',
    ADD COLUMN payment_expires_at TIMESTAMPTZ;
ALTER TABLE orders ADD CONSTRAINT orders_payment_status_check
    CHECK (payment_status IN ('UNPAID', 'PENDING', 'PAID', 'FAILED', 'EXPIRED', 'CANCELLED', 'REVIEW_REQUIRED'));
ALTER TABLE orders ADD CONSTRAINT orders_online_payment_expiry_check
    CHECK (payment_method <> 'VNPAY' OR payment_expires_at IS NOT NULL);
ALTER TABLE orders ADD CONSTRAINT orders_payment_method_status_check
    CHECK ((payment_method = 'COD' AND payment_status IN ('UNPAID', 'PAID'))
        OR (payment_method = 'VNPAY' AND payment_status <> 'UNPAID'));
CREATE INDEX idx_orders_pending_payment_expiry ON orders(payment_expires_at, id)
    WHERE payment_method = 'VNPAY' AND status = 'PENDING' AND payment_status = 'PENDING';
UPDATE orders SET payment_status = 'PAID' WHERE payment_method = 'COD' AND status = 'COMPLETED';

CREATE TABLE payment_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
    txn_ref VARCHAR(64) NOT NULL UNIQUE,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    payment_url TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'REVIEW_REQUIRED')),
    provider_transaction_no VARCHAR(30) UNIQUE,
    response_code VARCHAR(2),
    paid_at TIMESTAMPTZ,
    CHECK (expires_at > created_at),
    CHECK (status NOT IN ('PAID', 'REVIEW_REQUIRED') OR (provider_transaction_no IS NOT NULL AND paid_at IS NOT NULL))
);
