CREATE TABLE vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    type VARCHAR(20) NOT NULL CHECK (type IN ('FIXED', 'PERCENT')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    minimum_subtotal NUMERIC(14,2) NOT NULL CHECK (minimum_subtotal >= 0),
    maximum_discount NUMERIC(12,2) NOT NULL CHECK (maximum_discount > 0),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL CHECK (ends_at > starts_at),
    usage_limit INTEGER NOT NULL CHECK (usage_limit > 0),
    per_user_limit INTEGER NOT NULL CHECK (per_user_limit > 0),
    used_count INTEGER NOT NULL DEFAULT 0 CHECK (used_count >= 0 AND used_count <= usage_limit),
    target_user_id BIGINT REFERENCES users(id),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (type <> 'PERCENT' OR amount <= 100),
    CHECK (code = UPPER(code))
);
