CREATE INDEX idx_orders_voucher_user_status ON orders(voucher_id, user_id, status);
CREATE TABLE order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL
        CHECK (status IN ('PENDING','CONFIRMED','SHIPPING','DELIVERED','COMPLETED','CANCELLED')),
    actor VARCHAR(20) NOT NULL CHECK (actor IN ('CUSTOMER','ADMIN','SYSTEM')),
    occurred_at TIMESTAMPTZ NOT NULL,
    imported BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_order_history_order ON order_status_history(order_id, occurred_at, id);
INSERT INTO order_status_history(order_id, status, actor, occurred_at, imported)
SELECT id, status, 'SYSTEM', COALESCE(updated_at, created_at), TRUE FROM orders;
